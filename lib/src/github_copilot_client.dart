import 'dart:convert';
import 'package:http/http.dart' as http;

/// Represents a message in a Copilot chat conversation.
class CopilotMessage {
  /// The role of the author of this message.
  ///
  /// Typical values are `'system'`, `'user'`, and `'assistant'`.
  final String role;

  /// The content of the message.
  final String content;

  const CopilotMessage({required this.role, required this.content});

  Map<String, dynamic> toJson() => {
        'role': role,
        'content': content,
      };
}

/// Represents a single completion choice returned by the Copilot chat API.
class CopilotChoice {
  /// The zero-based index of this choice.
  final int index;

  /// The message generated by the model.
  final CopilotMessage message;

  /// The reason the model stopped generating tokens.
  final String? finishReason;

  const CopilotChoice({
    required this.index,
    required this.message,
    this.finishReason,
  });

  factory CopilotChoice.fromJson(Map<String, dynamic> json) {
    final messageJson = json['message'] as Map<String, dynamic>;
    return CopilotChoice(
      index: json['index'] as int,
      message: CopilotMessage(
        role: messageJson['role'] as String,
        content: messageJson['content'] as String,
      ),
      finishReason: json['finish_reason'] as String?,
    );
  }
}

/// Represents a response from the GitHub Copilot chat API.
class CopilotResponse {
  /// A unique identifier for the completion.
  final String id;

  /// The list of completion choices the model generated.
  final List<CopilotChoice> choices;

  const CopilotResponse({required this.id, required this.choices});

  factory CopilotResponse.fromJson(Map<String, dynamic> json) {
    return CopilotResponse(
      id: json['id'] as String,
      choices: (json['choices'] as List<dynamic>)
          .map((c) => CopilotChoice.fromJson(c as Map<String, dynamic>))
          .toList(),
    );
  }
}

/// Exception thrown when a GitHub Copilot API call fails.
class GitHubCopilotException implements Exception {
  /// A description of the error.
  final String message;

  /// The HTTP status code associated with the error, if available.
  final int? statusCode;

  const GitHubCopilotException(this.message, {this.statusCode});

  @override
  String toString() {
    if (statusCode != null) {
      return 'GitHubCopilotException: $message (HTTP $statusCode)';
    }
    return 'GitHubCopilotException: $message';
  }
}

/// A client for interacting with the GitHub Copilot chat API from Dart.
///
/// Requires a GitHub personal access token (classic) or fine-grained token
/// with access to GitHub Copilot.
///
/// Example:
/// ```dart
/// final client = GitHubCopilotClient(githubToken: 'ghp_yourtoken');
/// try {
///   final response = await client.chat([
///     CopilotMessage(role: 'user', content: 'Hello, Copilot!'),
///   ]);
///   print(response.choices.first.message.content);
/// } finally {
///   client.close();
/// }
/// ```
class GitHubCopilotClient {
  static const String _tokenUrl =
      'https://api.github.com/copilot_internal/v2/token';
  static const String _chatUrl =
      'https://api.githubcopilot.com/chat/completions';

  /// The version string reported to the Copilot API in the `Editor-Version`
  /// header. Matches the `version` field in `pubspec.yaml`.
  static const String _clientVersion = 'dart/1.0.3';

  /// The default model used for chat completions.
  static const String defaultModel = 'gpt-4';

  /// The GitHub personal access token used for authentication.
  final String githubToken;

  final http.Client _httpClient;

  /// Creates a [GitHubCopilotClient].
  ///
  /// [githubToken] must be a valid GitHub personal access token with Copilot
  /// access. An optional [httpClient] can be supplied for testing.
  GitHubCopilotClient({
    required this.githubToken,
    http.Client? httpClient,
  }) : _httpClient = httpClient ?? http.Client();

  /// Exchanges the GitHub personal access token for a short-lived Copilot
  /// API token.
  ///
  /// Throws [GitHubCopilotException] if the request fails.
  Future<String> _getCopilotToken() async {
    final response = await _httpClient.get(
      Uri.parse(_tokenUrl),
      headers: {
        'Authorization': 'token $githubToken',
        'Accept': 'application/json',
      },
    );

    if (response.statusCode != 200) {
      throw GitHubCopilotException(
        'Failed to obtain Copilot token',
        statusCode: response.statusCode,
      );
    }

    final json = jsonDecode(response.body) as Map<String, dynamic>;
    return json['token'] as String;
  }

  /// Sends a list of [messages] to the GitHub Copilot chat completions API
  /// and returns the model's response.
  ///
  /// [messages] - The conversation history. Typically begins with an optional
  /// `system` message followed by alternating `user` and `assistant` messages.
  ///
  /// [model] - The model identifier to use. Defaults to [defaultModel].
  ///
  /// Throws [GitHubCopilotException] if either the token exchange or the
  /// chat completion request fails.
  Future<CopilotResponse> chat(
    List<CopilotMessage> messages, {
    String model = defaultModel,
  }) async {
    final copilotToken = await _getCopilotToken();

    final response = await _httpClient.post(
      Uri.parse(_chatUrl),
      headers: {
        'Authorization': 'Bearer $copilotToken',
        'Content-Type': 'application/json',
        'Accept': 'application/json',
        'Editor-Version': _clientVersion,
        'Copilot-Integration-Id': 'dart-client',
      },
      body: jsonEncode({
        'model': model,
        'messages': messages.map((m) => m.toJson()).toList(),
      }),
    );

    if (response.statusCode != 200) {
      throw GitHubCopilotException(
        'Chat completion request failed',
        statusCode: response.statusCode,
      );
    }

    final json = jsonDecode(response.body) as Map<String, dynamic>;
    return CopilotResponse.fromJson(json);
  }

  /// Closes the underlying HTTP client and releases its resources.
  ///
  /// Must be called when the client is no longer needed.
  void close() {
    _httpClient.close();
  }
}
